const engine = new Engine(KB);
let passed = 0;
cases.forEach((c, i) => {
  const r = engine.run(c.a);
  const top = r.styles[0] ? r.styles[0].style : '-';
  const ok = top === c.top && (!c.advice || r.advice.length > 0);
  if (ok) passed++;
  const list = r.styles.slice(0, 3).map(s => s.style + ' ' + s.cf.toFixed(2)).join(', ');
  console.log((i + 1) + '. ' + c.name);
  console.log('   ожидалось: ' + c.top + ' | получено: ' + list + ' | правил сработало: ' + r.trace.length + ' | ' + (ok ? 'OK' : 'ОШИБКА'));
  if (r.advice.length) console.log('   совет: ' + r.advice.join('; '));
});
console.log('Пройдено ' + passed + ' из ' + cases.length);

console.log('\nТрасса вывода для сценария 2:');
